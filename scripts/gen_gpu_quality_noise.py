#!/usr/bin/env python3
"""Generate an original deterministic 64x64 toroidal void-and-cluster mask.
No downloaded textures/code; integer Gaussian energy, xorshift32 seed and
lowest-index ties make ranks independent of Python/libm/platform versions.
Algorithm reference: Ulichney (1993), explained by Christoph Peters:
https://momentsingraphics.de/BlueNoise.html (void and cluster method).
SPDX-License-Identifier: GPL-3.0-only
"""
import argparse, hashlib, json, pathlib, struct
SIDE=64
COUNT=4096
SEED=0x58433425
# Quantized 1D Gaussian sigma approximately 1.5; the 2D kernel is its product.
# All entries and all scoring operations are integers; there is no exp/libm.
KERNEL=(65536,52477,26943,8870,1872,253,22,1)
OFFSETS=[(dx,dy,KERNEL[abs(dx)]*KERNEL[abs(dy)])
         for dy in range(-7,8) for dx in range(-7,8)]
def construct():
    random_state=SEED
    indices=list(range(COUNT))
    for i in range(COUNT-1,0,-1):
        random_state^=(random_state<<13)&0xffffffff
        random_state^=random_state>>17
        random_state^=(random_state<<5)&0xffffffff
        random_state&=0xffffffff
        j=random_state%(i+1)
        indices[i],indices[j]=indices[j],indices[i]
    seed=[False]*COUNT
    for i in indices[:COUNT//8]:seed[i]=True
    energy=[0]*COUNT
    def update(index,sign):
        x=index&63;y=index>>6
        for dx,dy,value in OFFSETS:
            energy[(((y+dy)&63)<<6)|((x+dx)&63)]+=sign*value
    for i,active in enumerate(seed):
        if active:update(i,1)
    def cluster(pattern):
        return max((i for i in range(COUNT) if pattern[i]),key=lambda i:(energy[i],-i))
    def void(pattern):
        return min((i for i in range(COUNT) if not pattern[i]),key=lambda i:(energy[i],i))
    for relaxation in range(COUNT*16):
        removed=cluster(seed);seed[removed]=False;update(removed,-1)
        added=void(seed);seed[added]=True;update(added,1)
        if removed==added:break
    else:raise RuntimeError('void-and-cluster seed did not converge')
    saved_energy=energy[:]
    ranks=[-1]*COUNT;pattern=seed[:]
    for rank in range(sum(seed)-1,-1,-1):
        index=cluster(pattern);pattern[index]=False;ranks[index]=rank;update(index,-1)
    pattern=seed[:];energy[:]=saved_energy
    for rank in range(sum(seed),COUNT//2):
        index=void(pattern);pattern[index]=True;ranks[index]=rank;update(index,1)
    # Above half coverage, the remaining zeros form the complementary mask.
    pattern=[not value for value in pattern];energy[:]=[0]*COUNT
    for i,active in enumerate(pattern):
        if active:update(i,1)
    for rank in range(COUNT//2,COUNT):
        index=cluster(pattern);pattern[index]=False;ranks[index]=rank;update(index,-1)
    assert sorted(ranks)==list(range(COUNT))
    return ranks,relaxation+1

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--header',type=pathlib.Path,required=True)
    p.add_argument('--report',type=pathlib.Path)
    a=p.parse_args();ranks,relaxation=construct()
    raw=struct.pack('<4096H',*ranks);sha=hashlib.sha256(raw).hexdigest()
    lines=['/* SPDX-License-Identifier: GPL-3.0-only */',
           '/* Generated by scripts/gen_gpu_quality_noise.py; do not edit.',
           ' * Original integer void-and-cluster, seed 0x58433425.',
           ' * Little-endian uint16 ranks SHA-256: '+sha+' */',
           '#pragma once','#include <stdint.h>',
           '#define X4_GPU_QUALITY_NOISE_SHA256 "'+sha+'"',
           'static const uint16_t x4_gpu_quality_noise[4096]={']
    lines+=['    '+','.join(str(x) for x in ranks[i:i+16])+',' for i in range(0,COUNT,16)]
    lines+=['};','']
    a.header.parent.mkdir(parents=True,exist_ok=True)
    a.header.write_text('\n'.join(lines),encoding='utf-8',newline='\n')
    report={'algorithm':'original integer toroidal void-and-cluster',
            'seed':SEED,'side':SIDE,'ranks':COUNT,'unique_ranks':len(set(ranks)),
            'minimum':min(ranks),'maximum':max(ranks),'mean':sum(ranks)/COUNT,
            'relaxations':relaxation,'rank_bytes_sha256':sha,
            'threshold':'(rank+0.5)/4096; fixed x/y, no frame index',
            'reference':'https://momentsingraphics.de/BlueNoise.html'}
    if a.report:a.report.write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(report,sort_keys=True))
if __name__=='__main__':main()
