#!/usr/bin/env python3
"""Compile the independent portable GPU kernels to strict LLVM gfx700 IR.
Only the C entry ABI, host-only metadata and target attributes are rewritten.
Arithmetic, buffer intrinsics and buffer offsets are kept from Clang output.
SPDX-License-Identifier: GPL-3.0-only
"""
import argparse, hashlib, json, pathlib, re, subprocess, tempfile
NAMES=('quality_direct','quality_prepare','quality_finish')
SIGNATURE='<4 x i32> inreg %yb, <4 x i32> inreg %uvb, <4 x i32> inreg %out, <4 x i32> inreg %params, i32 inreg %gx, i32 inreg %gy, i32 %tx, i32 %ty'
def convert(text,name):
    text=re.sub(r'^target (?:datalayout|triple) = .*\n','',text,flags=re.M)
    text=re.sub(r'^source_filename = .*\n','',text,flags=re.M)
    text=re.sub(r'^; ModuleID = .*\n','',text,flags=re.M)
    text=re.sub(r'%prm\b','%params',text)
    definitions=re.findall(r'^define .*',text,re.M)
    if len(definitions)!=1 or '@main(' not in definitions[0]:
        raise ValueError('all kernel helpers must inline, with one main entry')
    text=re.sub(r'^define .*@main\(.*\).*\{\s*$',
                'define amdgpu_cs void @main('+SIGNATURE+') #0 {',text,flags=re.M)
    text=re.sub(r'^attributes #\d+ = .*\n','',text,flags=re.M)
    # Remove the old attribute references but preserve our new kernel #0.
    text=re.sub(r' #\d+(?![^\n]*\{)', '',text)
    text=re.sub(r'^![^\n]*\n','',text,flags=re.M)
    text=re.sub(r', ![a-zA-Z0-9_.]+ !\d+','',text)
    text=re.sub(r' #[1-9]\d*\b','',text)
    if re.search(r'\b(?:alloca|fdiv|frem)\b|llvm\.(?:sqrt|pow|fma|fmuladd)|\b(?:fast|reassoc|contract|arcp|afn|nsz)\b',text):
        raise ValueError('quality arithmetic requires strict add/mul/bitcasts without stack/div/sqrt/FMA')
    if re.search(r'^@',text,re.M):raise ValueError('kernel must not reference global storage/relocations')
    if any(x in text for x in ('x86','sse','target-cpu','target-features')):
        raise ValueError('host target metadata survived kernel adaptation')
    header=('; SPDX-License-Identifier: GPL-3.0-only\n'
            '; Generated by scripts/gen_gpu_quality_ir.py from gpu_quality_kernel.c.\n'
            '; AMD CAS MIT 9fabcc9a2c45f958aff55ddfda337e74ef894b7f; notices in docs/licenses.\n'
            '; Strict binary32 add/mul, explicit integer-bit seeds, no approximation ISA.\n'
            '; USER_DATA Y/UV/output/parameters V# s0:15; groups s16/s17; local v0/v1.\n'
            '; user_sgprs=16\n; tgid_y=1\n; local_y=1\n; threads_x=8\n; threads_y=8\n'
            'target triple = "amdgcn--"\n')
    return header+text.strip()+'\nattributes #0 = { "amdgpu-flat-work-group-size"="64,64" "fp-contract"="off" }\n'
def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--clang',required=True)
    p.add_argument('--output',type=pathlib.Path,required=True)
    p.add_argument('--report',type=pathlib.Path)
    a=p.parse_args();source=pathlib.Path(__file__).with_name('gpu_quality_kernel.c')
    version=subprocess.run([a.clang,'--version'],check=True,text=True,capture_output=True).stdout
    if not re.search(r'clang version 21\.1\.8\b',version):
        raise ValueError('quality regeneration requires pinned Clang 21.1.8')
    a.output.mkdir(parents=True,exist_ok=True);report={}
    with tempfile.TemporaryDirectory(prefix='x4-quality-ir-') as temp:
        for mode,name in enumerate(NAMES):
            raw=pathlib.Path(temp)/(name+'.ll')
            command=[a.clang,'-std=c17','-O2','-fno-vectorize','-fno-slp-vectorize',
                     '-ffreestanding','-fno-stack-protector','-fno-fast-math','-ffp-contract=off',
                     '-fno-discard-value-names','-S','-emit-llvm','-DX4_QUALITY_PASS='+str(mode),
                     str(source),'-o',str(raw)]
            result=subprocess.run(command,text=True,capture_output=True)
            if result.returncode:raise RuntimeError(result.stderr)
            if result.stderr.strip():raise ValueError('kernel generation produced diagnostics: '+result.stderr)
            adapted=convert(raw.read_text(),name)
            destination=a.output/(name+'.ll');destination.write_text(adapted,encoding='utf-8',newline='\n')
            report[name]={'sha256':hashlib.sha256(adapted.encode()).hexdigest(),
                          'bytes':len(adapted.encode()),'pass':mode,'strict_fp':True}
    value={'clang_version':version.splitlines()[0],
           'kernel_source_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'shaders':report}
    if a.report:a.report.write_text(json.dumps(value,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(value,sort_keys=True))
if __name__=='__main__':main()
